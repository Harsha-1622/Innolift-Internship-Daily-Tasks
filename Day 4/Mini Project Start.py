# Project Name:
# Household Energy Consumption Forecaster - IOT

# ------------------------------------------------------------
# Dataset
# ------------------------------------------------------------

# Dataset Name:
# Household Power Consumption Dataset (household_power_consumption.csv)

# Description:
# This dataset contains real-world household electricity
# consumption measurements collected over a long period.
# It includes various electrical parameters such as
# active power, reactive power, voltage, current intensity,
# and sub-metering values.

# The dataset is suitable for machine learning because it
# contains historical energy usage data that can be used
# to predict future household power consumption.

# ------------------------------------------------------------
# Features (X Columns)
# ------------------------------------------------------------

# The following input features will be used to train
# the machine learning model:

# 1. Global_reactive_power
#    - Represents reactive power consumed by the household.

# 2. Voltage
#    - Indicates the electrical voltage supplied.

# 3. Global_intensity
#    - Represents the total current intensity used.

# 4. Sub_metering_3
#    - Measures energy consumption in a specific area
#      of the household.

# These features were selected because they directly
# influence overall household energy consumption and
# help improve prediction accuracy.

# ------------------------------------------------------------
# Target Variable (Y Column)
# ------------------------------------------------------------

# Target Column:
# Global_active_power

# Description:
# Global Active Power represents the actual power
# consumed by the household.

# The objective of the model is to predict this value
# based on the selected input features.

# ------------------------------------------------------------
# Problem Statement
# ------------------------------------------------------------

# Electricity consumption is increasing due to the
# growing use of electrical appliances and smart devices.

# Many households do not have a clear understanding
# of their future energy usage, which can result in
# inefficient energy management and higher electricity bills.

# This project aims to develop a Machine Learning model
# that predicts household energy consumption using
# historical electrical measurements.

# ------------------------------------------------------------
# Question the Model Will Answer
# ------------------------------------------------------------

# "Based on household electrical parameters such as
# reactive power, voltage, current intensity, and
# sub-metering values, what will be the expected
# Global Active Power Consumption?"

# ------------------------------------------------------------
# Expected Outcome
# ------------------------------------------------------------

# The trained Machine Learning model will learn patterns
# from historical energy consumption data and predict
# future household power usage.

# The predictions can help users:

# - Monitor electricity consumption
# - Reduce electricity bills
# - Improve energy efficiency
# - Optimize appliance usage
# - Understand power consumption patterns

# ------------------------------------------------------------
