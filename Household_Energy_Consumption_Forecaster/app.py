# ==========================================
# IMPORTS
# ==========================================

from flask import Flask, render_template

# ==========================================
# CREATE APP
# ==========================================

app = Flask(__name__)

# ==========================================
# HOME ROUTE
# ==========================================

@app.route('/')

def home():

    return render_template(
        'index.html'
    )

# ==========================================
# RUN APP
# ==========================================

if __name__ == '__main__':

    app.run(
        debug=True
    )